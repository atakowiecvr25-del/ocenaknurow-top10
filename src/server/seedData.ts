function makeBatchReviews(
  placeId: string,
  ratings: number[],
  authors: string[],
  comments: string[],
  baseDate: string,
  distanceKm: number
): Review[] {
  const baseMs = new Date(baseDate).getTime();
  return ratings.map((rating, idx) => ({
    id: `seed-${placeId}-${idx + 1}`,
    placeId,
    userId: `google-seed-${idx + 1}`,
    authorName: authors[idx % authors.length],
    authorAvatar: '',
    rating,
    comment: comments[idx % comments.length],
    isLocalVerified: true,
    distanceKm: Math.round((distanceKm + (idx % 4) * 0.35) * 100) / 100,
    createdAt: new Date(baseMs - idx * 86400000 * 3).toISOString(),
  }));
}

